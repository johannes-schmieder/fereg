//! Counter-based signs: numeric unit bits and probe index; no shared RNG state.
use crate::error::{ErrorCode, FeregError, Result};
pub fn sign(seed: u32, stream: u32, unit: f64, probe: u32) -> Result<f64> {
    if !unit.is_finite() {
        return Err(FeregError::new(
            ErrorCode::InvalidData,
            "bias probe unit must be finite",
        ));
    }
    let bits = if unit == 0. { 0 } else { unit.to_bits() };
    let output = words([bits as u32, (bits >> 32) as u32, probe, 0], [seed, stream]);
    Ok(if output[0] & 1 == 0 { -1. } else { 1. })
}
fn words(mut c: [u32; 4], mut k: [u32; 2]) -> [u32; 4] {
    for round in 0..10 {
        let p0 = 0xD2511F53_u64 * u64::from(c[0]);
        let p1 = 0xCD9E8D57_u64 * u64::from(c[2]);
        c = [
            (p1 >> 32) as u32 ^ c[1] ^ k[0],
            p1 as u32,
            (p0 >> 32) as u32 ^ c[3] ^ k[1],
            p0 as u32,
        ];
        if round != 9 {
            k[0] = k[0].wrapping_add(0x9E3779B9);
            k[1] = k[1].wrapping_add(0xBB67AE85);
        }
    }
    c
}
#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn pinned_random123_known_answers() {
        // SPEC's Random123 d8a0c25e tests/kat_vectors; verified SHA-256
        // aab5ebabf40003f63d6d87b24cbd2c8a02652e00cf8bad64226fd50586929183.
        for (counter, key, expected) in [
            (
                [0; 4],
                [0; 2],
                [0x6627e8d5, 0xe169c58d, 0xbc57ac4c, 0x9b00dbd8],
            ),
            (
                [u32::MAX; 4],
                [u32::MAX; 2],
                [0x408f276d, 0x41c83b0e, 0xa20bc7c6, 0x6d5451fd],
            ),
            (
                [0x243f6a88, 0x85a308d3, 0x13198a2e, 0x03707344],
                [0xa4093822, 0x299f31d0],
                [0xd16cfe09, 0x94fdcceb, 0x5001e420, 0x24126ea1],
            ),
        ] {
            assert_eq!(words(counter, key), expected);
        }
    }
    #[test]
    fn signed_zero_and_invalid_unit_contracts() {
        for probe in [0, 1, 127, u32::MAX] {
            assert_eq!(sign(17, 3, -0., probe), sign(17, 3, 0., probe));
        }
        assert_eq!(sign(0, 0, 0., 0).unwrap(), 1.);
        for unit in [f64::NAN, f64::INFINITY, f64::NEG_INFINITY] {
            assert_eq!(
                sign(17, 3, unit, 0).unwrap_err().code,
                ErrorCode::InvalidData
            );
        }
    }
    #[test]
    fn numeric_identity_and_stream_masks_match_the_independent_vectorized_oracle() {
        // Generated by scripts/ppml_bias_oracle.py::philox_signs, not this kernel.
        for (seed, stream, unit, expected) in [
            (0, 0, 0., 0xff3ee422b2ea0ad7_u64),
            (739391, 0, 0., 0xabfad0f48b236a5e),
            (17, 1, 42., 0x56fa2e0513728226),
            (17, 2, 42., 0xdac01e591c4f0e84),
            (u32::MAX, u32::MAX, -3.5, 0x1fc3fbc74c73998c),
            (739391, 0, 1e-300, 0x258d4e62e6898e07),
            (739391, 0, 1e300, 0x4e8635ad9ce806d9),
        ] {
            let mut actual = 0_u64;
            for probe in 0..64 {
                if sign(seed, stream, unit, probe).unwrap() == 1. {
                    actual |= 1 << probe;
                }
            }
            assert_eq!(actual, expected);
        }
    }
}
